"""Rewrite absolute home paths under `docs/` and `openspec/` as placeholders.

    python3 docs/receipts/post43/redact_paths.py

  <repo> the checkout a receipt was produced from
  <hermes-home> the Hermes install and its data root
  <home> anything else under a user's home directory

post-#42 wrote this for `docs/receipts/` alone. The tree it has to keep clean is
now `docs/` and `openspec/` — the check in `tests/test_receipt_paths.py` scans
both, because a readiness note, a review record and a change's `verification.md`
are evidence documents like any receipt — so the walk is the two roots.

`run-suite.sh` calls this as its last step, because the logs it has just written
carry a home path in them (pytest's warning summary names the venv's site-packages
file) and the check scans the tree as it stands on disk.

Byte-level, so binary files are untouched, and only files that contain one of the
prefixes are rewritten: a receipt's measured content changes only where a path
appears. The prefixes are assembled from pieces so that this file cannot match
itself.
"""
import os
import re
import shutil
import sys

OUT = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(OUT)))
ROOTS = [os.path.join(REPO, "docs"), os.path.join(REPO, "openspec")]
# Built at RUNTIME, not compiled: `b"/" + b"Users" + b"/robert"` is constant-folded
# into the very token this script rewrites, and the folded bytes then sit in this
# module's `.pyc` under the tree it is supposed to keep clean. `drop_bytecode()`
# below removes any that a stray run left behind.
SLASH = chr(47)
USER_HOME = (SLASH + "Users" + SLASH + "robert").encode()
HOME_PREFIX = (SLASH + "home").encode()

PATTERN = re.compile(re.escape((SLASH + "Users").encode()) + rb"/|" + re.escape(HOME_PREFIX) + rb"/")
RULES = [
    # A checkout that is NOT this one keeps its own suffix, so `<repo>` never
    # claims a run that happened somewhere else.
    (re.compile(re.escape(USER_HOME + b"/Developer/hackertube-3.3")), b"<home>/Developer/hackertube-3.3"),
    (re.compile(re.escape(USER_HOME + b"/Developer/hackertube")), b"<repo>"),
    (re.compile(re.escape(USER_HOME + b"/.hermes")), b"<hermes-home>"),
    (re.compile(re.escape(USER_HOME + b"/")), b"<home>/"),
    (re.compile(re.escape(USER_HOME) + rb"\b"), b"<home>"),
    (re.compile(re.escape(HOME_PREFIX) + rb"/[A-Za-z0-9_.-]+"), b"<home>"),
]


def redact(paths=None):
    changed = []
    for path in paths if paths is not None else walk_all():
        try:
            with open(path, "rb") as handle:
                data = handle.read()
        except OSError:
            continue
        if not PATTERN.search(data):
            continue
        new = data
        for pattern, replacement in RULES:
            new = pattern.sub(replacement, new)
        if new != data:
            with open(path, "wb") as handle:
                handle.write(new)
            changed.append(os.path.relpath(path, REPO))
    return changed


def walk(root):
    for dirpath, _, names in os.walk(root):
        for name in names:
            yield os.path.join(dirpath, name)


def walk_all():
    for root in ROOTS:
        for path in walk(root):
            if not path.endswith(".pyc"):
                yield path


def drop_bytecode():
    """Remove `__pycache__` directories under the scanned roots.

    Generated bytecode is not authored content, and a module that assembles one of
    the forbidden prefixes at import time leaves the assembled bytes in its `.pyc`
    — which would then fail the very check this script exists to keep green.
    """
    removed = []
    for root in ROOTS:
        for dirpath, dirnames, _ in os.walk(root):
            for name in list(dirnames):
                if name == "__pycache__":
                    target = os.path.join(dirpath, name)
                    shutil.rmtree(target, ignore_errors=True)
                    dirnames.remove(name)
                    removed.append(os.path.relpath(target, REPO))
    return removed


def main():
    changed = redact()
    dropped = drop_bytecode()
    print(f"{len(changed)} file(s) rewritten to placeholder paths")
    for path in sorted(changed):
        print(" ", path)
    print(f"{len(dropped)} __pycache__ director(y|ies) removed: {', '.join(dropped) if dropped else 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
